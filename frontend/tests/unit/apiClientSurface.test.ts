test("api facade exposes every pinned public method", () => {
    const bag = api as unknown as Record<string, unknown>;
    const missing = EXPECTED_PUBLIC_METHODS.filter(
        (name) => typeof bag[name] !== "function",
    );
    assert.deepEqual(missing, [], `missing api methods: ${missing.join(", ")}`);
});

test("api facade public surface count is pinned", () => {
    assert.equal(EXPECTED_PUBLIC_METHODS.length, 289);
});
